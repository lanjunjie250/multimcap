import assert from 'node:assert/strict';
import {HandContinuity,HOLD_MS} from '../rtcamera_offline/web/analysis/continuity.js';
import {drawHands,HAND_COLOR} from '../rtcamera_offline/web/analysis/overlay.js';
const hand=(x,label='Left')=>({label,score:.9,landmarks:Array.from({length:21},(_,i)=>({x:x+(i%5)*.01,y:.5+Math.floor(i/5)*.01,z:0}))});
const c=new HandContinuity();
const result=(i,hands)=>({key:'r:0:'+i,hands});
const a=hand(.2),b=hand(.7,'Right');
c.update(result(0,[a,b]),0);
let r=c.update(result(1,[a]),33);
assert.equal(r.detectedCount,1);assert.equal(r.heldCount,1);
assert.equal(r.hands[1].sourceKey,'r:0:0');assert.equal(r.hands[1].held,true);
assert.equal(c.update(result(1,[a]),33),r,'duplicate cached delivery does not refresh or consume hold');
r=c.update(result(2,[hand(.71,'Left'),hand(.21,'Right')]),66);
assert.equal(r.heldCount,0,'reordered/flipped classifications do not duplicate tracks');
assert.equal(c.update(result(3,[]),99).heldCount,2);
assert.equal(c.update(result(4,[]),132).heldCount,2);
assert.equal(c.update(result(5,[]),155).heldCount,0,'third miss expires even within time limit');
c.reset();c.update(result(0,[a]),0);
assert.equal(c.update(result(1,[]),HOLD_MS+1).hands.length,0,'skipped frames cannot extend retention');
c.reset();c.update(result(5,[a]),500);
assert.equal(c.update(result(2,[]),100).hands.length,0,'backwards seek resets');
c.update(result(3,[a]),133);
assert.equal(c.update({key:'other:0:4',hands:[]},166).hands.length,0,'recording switch resets');
c.update(result(5,[a]),200);c.reset();
assert.equal(c.update(result(6,[]),233).hands.length,0,'disable/reset clears retention');
c.reset();c.update(result(0,[a,b]),0);
assert.equal(c.update(result(1,[hand(.22)]),33,1).hands.length,1,'respect user maximum');
const strokes=[],ctx={clearRect(){},beginPath(){},moveTo(){},lineTo(){},stroke(){strokes.push(this.strokeStyle);},arc(){},fill(){}};
c.reset();c.update(result(0,[a]),0);
assert.equal(c.update(result(1,[b]),33).hands.length,1,'fast movement or a new hand must not create a ghost duplicate');
const canvas={width:640,height:480,getContext(){return ctx;}};
drawHands(canvas,{hands:[hand(.2,'Left'),hand(.7,'Right'),hand(.4,'Unknown')]});
assert.deepEqual(strokes,[HAND_COLOR,HAND_COLOR,HAND_COLOR]);
console.log('Hand continuity: partial loss, identity reorder, bounded misses/time, provenance, reset and fixed color passed.');
